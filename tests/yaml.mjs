// The emitter writes files that kitctl (ruamel) and Gestalt (yaml.mjs) both read back.
// A scalar that changes type on the way back (`on` → true, `1.0` → 1) silently changes a
// loadout, so every hazard round-trips here.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { check, finish, group, ROOT } from "./harness.mjs";
import { parseYaml } from "../tools/lib/yaml.mjs";
import { emitYaml, scalar } from "../tools/lib/yaml-emit.mjs";

const roundTrip = doc => parseYaml(emitYaml(doc));

group("yaml reader (pinned copy)");
check("yaml.mjs is byte-identical to ui-magic@ce95d3a", "a silent local edit would fork the parser from the one tested against PyYAML upstream", () => {
  const sha = createHash("sha256").update(readFileSync(join(ROOT, "tools/lib/yaml.mjs"))).digest("hex");
  assert.equal(sha, "261e13725a2aaf9473b06dd4ec91a962e07f59bfbe8b81be88433fca198a5eec");
});

group("yaml emitter");
check("hazard strings stay strings", "`on`, `yes`, `null`, `1.0` and `5364e38` change type in YAML readers; a loadout would change meaning", () => {
  const hazards = ["on", "yes", "No", "null", "~", "true", "1.0", "5364e38", "0x1F", "007", "a: b", "a #b", "- x", "* y", "&z", "!t", "@at", "`tick`", "", " lead", "trail ", "file-exists:BRAND.md", "mcp:linear", "${plugin:x}/scripts/a.mjs", "[x]", "{y}", "'q'", "\"dq\"", "%p", "|", ">"];
  const back = roundTrip({ list: hazards, ...Object.fromEntries(hazards.map((h, i) => [`k${i}`, h])) });
  assert.deepEqual(back.list, hazards);
  hazards.forEach((h, i) => assert.equal(back[`k${i}`], h, h));
});
check("YAML 1.1 booleans are quoted", "kitctl reads with ruamel; an unquoted `on` is true to a 1.1 reader", () => {
  for (const s of ["on", "off", "yes", "no", "y", "n", "Y", "ON"]) assert.equal(scalar(s), JSON.stringify(s));
});
check("nested maps, lists of maps, empties", "loadout profiles and mcp entries are maps inside lists inside maps", () => {
  const doc = { schema_version: 2, name: "x", plugins: [], mcp: {}, hooks: [{ event: "Stop", blocking: true, args: ["a", "b"] }], profiles: { audit: { description: "Read-only", plugins: ["plugin:x"], hooks: [] } }, nested: [[1, 2], ["a"]] };
  assert.deepEqual(roundTrip(doc), doc);
});
check("multi-line strings use block scalars and round-trip", "the instructions field carries the managed block body", () => {
  const doc = { a: "line one\nline two\n", b: "no trailing newline\nsecond", c: "keep\n\n", d: "  indented first\nx" };
  const text = emitYaml(doc);
  assert.match(text, /a: \|\n  line one/);
  assert.deepEqual(parseYaml(text), doc);
});
check("long scalar lists fall back to block style", "flow lines past ~96 columns are unreadable in review diffs", () => {
  const list = Array.from({ length: 12 }, (_, i) => `plugin:some-long-plugin-name-${i}`);
  const text = emitYaml({ disable: list });
  assert.match(text, /disable:\n  - plugin:some-long-plugin-name-0/);
  assert.deepEqual(parseYaml(text).disable, list);
});
check("header comments", "every generated file says it is generated", () => {
  const text = emitYaml({ a: 1 }, { header: ["Generated by gestalt.", ""] });
  assert.ok(text.startsWith("# Generated by gestalt.\n#\na: 1\n"));
});
check("emitter output is stable", "compile goldens are byte-compared", () => {
  const doc = { b: [1, "x"], a: { z: null, y: false } };
  assert.equal(emitYaml(doc), emitYaml(JSON.parse(JSON.stringify(doc))));
});

finish();
