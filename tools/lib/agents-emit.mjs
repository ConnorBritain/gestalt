// Worker definitions. A subagent becomes a non-plugin agent file (plugin agents ignore
// mcpServers), a headless worker becomes a launch script plus its MCP config, and every
// worker carries the hand-off contract. Codex custom agents are emitted labelled
// unverified: their fields come from documentation snippets, not a tested CLI.
import { command } from "./block.mjs";
import { emitYaml } from "./yaml-emit.mjs";

export const GENERATED = "Generated by gestalt compile";

const CONTRACT = [
  "You are a worker. The lead has handed you one job.",
  "",
  "- Work only from what the lead passed you: the user's original request, verbatim, and every decision the user has made since. If either is missing, say so in one line and stop; do not guess the intent.",
  "- Do the job with the steps below and nothing else. Do not widen it.",
  "- Return only what is asked for under Returns. The lead decides what happens next.",
];

function stepsText(worker, catalog) {
  return worker.uses.map(u => {
    const s = catalog.steps.get(u);
    const cmd = s ? command(s) : null;
    return `- ${u}: ${s?.invoke ?? "(unknown step)"}${cmd ? ` (\`${cmd}\`)` : ""}`;
  });
}

function mcpServersFor(worker, way) {
  const inline = {};
  const shared = [];
  for (const id of worker.mcp) {
    const c = way.connectors.find(x => x.id === id);
    if (c?.server) inline[id] = c.server;
    else shared.push(id);
  }
  return { inline, shared };
}

export function emitAgents(way, catalog) {
  const files = {};
  for (const w of way.topology.workers) {
    const model = way.topology.tiers.claude?.[w.tier];
    const body = [...CONTRACT, "", "## Steps", "", ...stepsText(w, catalog), "", "## Returns", "", w.returns ?? "A short result: what you did, where it is, and anything the lead must decide."].join("\n");
    const { inline, shared } = mcpServersFor(w, way);
    if (w.mechanism === "subagent" && way.harnesses.includes("claude")) {
      const fm = { name: w.id, description: `Use for ${w.route}. ${GENERATED}; edit the way, not this file.` };
      if (model) fm.model = model;
      const servers = [...shared, ...Object.entries(inline).map(([k, v]) => ({ [k]: v }))];
      if (servers.length) fm.mcpServers = servers;
      files[`agents/claude/${w.id}.md`] = `---\n${emitYaml(fm)}---\n\n${body}\n`;
    }
    if (w.mechanism === "headless") {
      const mcpFile = Object.keys(inline).length ? `${w.id}.mcp.json` : null;
      if (mcpFile) files[`workers/${mcpFile}`] = `${JSON.stringify({ mcpServers: inline }, null, 2)}\n`;
      const pluginVars = [...new Set(w.uses.map(u => catalog.steps.get(u)?.entry).filter(e => e && e.ref.startsWith("plugin:")).map(e => e.id))];
      const env = id => `GESTALT_PLUGIN_${id.toUpperCase().replace(/[^A-Z0-9]/g, "_")}`;
      const lines = [
        "#!/bin/sh",
        `# ${GENERATED}: headless worker "${w.id}" (${w.tier} tier).`,
        `# Route: ${w.route}`,
        "# Usage: sh " + `${w.id}.sh "<task, with the user's original request verbatim and decisions since>"`,
        "# The worker loads only its own plugins and MCP servers; the lead loads neither.",
        ...pluginVars.map(id => `# Set ${env(id)} to the ${id} plugin directory (see SETUP.md).`),
        ...(pluginVars.length ? ["# Unverified: that --plugin-dir loads a plugin the lead's settings disable. Check once (SETUP.md §5)."] : []),
        'set -eu',
        'HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)',
        `PROMPT="$(cat "$HERE/${w.id}.prompt.md")`,
        '${1:?pass the task}"',
        `exec claude -p${model ? ` --model ${model}` : ""} --strict-mcp-config${mcpFile ? ` --mcp-config "$HERE/${mcpFile}"` : ""}${pluginVars.map(id => ` --plugin-dir "\${${env(id)}:?set ${env(id)} to the ${id} plugin directory}"`).join("")} "$PROMPT"`,
      ];
      const codexModel = way.topology.tiers.codex?.[w.tier];
      if (way.harnesses.includes("codex")) lines.push(`# Codex alternative (unverified flags): codex exec${codexModel ? ` -m ${codexModel}` : ""} "$PROMPT"`);
      files[`workers/${w.id}.sh`] = `${lines.join("\n")}\n`;
      files[`workers/${w.id}.prompt.md`] = `<!-- ${GENERATED}; edit the way, not this file. -->\n${body}\n\n## Task\n`;
    }
    if ((w.mechanism === "subagent" || w.mechanism === "headless") && way.harnesses.includes("codex")) {
      const codexModel = way.topology.tiers.codex?.[w.tier];
      const toml = [
        `# ${GENERATED}. Codex custom agent for worker "${w.id}".`,
        "# UNVERIFIED: field names come from Codex documentation, not a tested CLI. Check with the installed Codex before relying on them.",
        `name = ${JSON.stringify(w.id)}`,
        `description = ${JSON.stringify(`Use for ${w.route}.`)}`,
        ...(codexModel ? [`model = ${JSON.stringify(codexModel)}`] : []),
        `developer_instructions = """\n${body.replace(/"""/g, '\\"\\"\\"')}\n"""`,
      ];
      files[`agents/codex/${w.id}.toml`] = `${toml.join("\n")}\n`;
    }
  }
  return files;
}
