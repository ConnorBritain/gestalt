// kitctl output. Gestalt never writes native config: it emits loadouts (schema_version 2)
// and per-context kit.yaml intents for kitctl to plan, preview and apply. The managed block
// travels as a loadout's `instructions`, so kitctl owns that text too. Subagent workers
// become `agent:` primitives (their rendered files beside them, copied verbatim by kitctl),
// and the lead's always-on budget travels as `budget` for `kitctl doctor` to hold.
import { activeEntries, leadEntries, scenarios } from "./way.mjs";
import { emitYaml } from "./yaml-emit.mjs";

export const V2_LOADOUT_KEYS = ["schema_version", "name", "description", "extends", "skills", "mcp", "hooks", "plugins", "marketplaces", "slots", "disable", "requires", "optional", "setup", "instructions", "profiles", "agents", "budget"];
const KIT_HARNESSES = ["claude", "codex"];
const HEADER = ["Generated by gestalt compile from way.yaml. Edit the way, not this file.", "kitctl owns what this writes: kitctl plan, then kitctl apply."];
// kitctl's agent asset file per harness (kitctl copies it verbatim to .claude/agents/<name>.md
// and .codex/agents/<name>.toml); Cursor has none.
const AGENT_ASSETS = { claude: ["claude.md", id => `agents/claude/${id}.md`], codex: ["codex.toml", id => `agents/codex/${id}.toml`] };

/** kitctl's budget: {tokens, skills}, keeping only positive integers. */
function budgetOf(budgets) {
  const b = { tokens: budgets.always_on_tokens, skills: budgets.skills_per_context };
  for (const k of Object.keys(b)) if (!Number.isInteger(b[k]) || b[k] <= 0) delete b[k];
  return b;
}

function loadoutFor(name, description, entries, way, disable, instructions, { agents = [], budget = {} } = {}) {
  const plugins = [...new Set(entries.filter(e => e.ref.startsWith("plugin:")).map(e => e.ref))].sort();
  // kitctl enables a plugin only; Claude Code and Codex find it through the marketplace the loadout also lists.
  const marketplaces = [...new Set(entries.filter(e => e.ref.startsWith("plugin:") && e.marketplace).map(e => e.marketplace))].sort();
  const skills = [...new Set(entries.filter(e => e.ref.startsWith("skill:")).map(e => e.ref))].sort();
  const mcp = {};
  for (const e of entries.filter(x => x.ref.startsWith("mcp:"))) mcp[e.ref.slice(4)] = { primitive: e.ref };
  const slots = {};
  for (const e of entries) if (e.slot) slots[e.slot] = e.ref;
  const doc = { schema_version: 2, name, description, extends: [], marketplaces, plugins, skills, agents: [...agents].sort(), mcp, slots, disable: [...disable].sort(), budget };
  if (instructions) doc.instructions = instructions;
  for (const k of Object.keys(doc)) {
    if (Array.isArray(doc[k]) && doc[k].length === 0 && k !== "extends") delete doc[k];
    else if (doc[k] && typeof doc[k] === "object" && !Array.isArray(doc[k]) && Object.keys(doc[k]).length === 0) delete doc[k];
  }
  return doc;
}

/**
 * Each way profile becomes a kitctl profile of every Gestalt loadout, so `<loadout>:<profile>`
 * works for all of them. kitctl profiles narrow and never add, so a profile carries only the
 * block lines it adds (`instructions_append`); lint (GST-PROFILE) keeps it from needing more.
 */
function withProfiles(doc, baseBody, profileBodies, { budgets = null } = {}) {
  if (!profileBodies.length) return;
  const have = new Set(baseBody.split("\n"));
  doc.profiles = {};
  for (const [pr, body] of profileBodies) {
    const extra = body.split("\n").filter(l => l.startsWith("- ") && !have.has(l));
    // A profile whose budgets change the lead's limits carries its own kitctl budget.
    const own = budgets && (pr.way.budgets.always_on_tokens !== budgets.always_on_tokens || pr.way.budgets.skills_per_context !== budgets.skills_per_context) ? budgetOf(pr.way.budgets) : {};
    doc.profiles[pr.name] = { description: pr.description, ...(extra.length ? { instructions_append: `${extra.join("\n")}\n` } : {}), ...(Object.keys(own).length ? { budget: own } : {}) };
  }
}

/**
 * Each subagent worker as a kitctl `agent:` primitive: primitives/agents/<id>.yaml, plus the
 * files emitAgents rendered, copied byte for byte into primitives/agents/<id>/.
 */
function agentPrimitives(way, agentFiles, files) {
  const refs = [];
  for (const w of way.topology.workers.filter(x => x.mechanism === "subagent")) {
    const harnesses = Object.keys(AGENT_ASSETS).filter(h => agentFiles[AGENT_ASSETS[h][1](w.id)] != null);
    if (!harnesses.length) continue;
    files[`primitives/agents/${w.id}.yaml`] = emitYaml({ schema_version: 2, kind: "agent", name: w.id, description: `Use for ${w.route}.`, harnesses }, { header: [...HEADER, `kitctl copies the files in primitives/agents/${w.id}/ verbatim (one per harness).`] });
    for (const h of harnesses) files[`primitives/agents/${w.id}/${AGENT_ASSETS[h][0]}`] = agentFiles[AGENT_ASSETS[h][1](w.id)];
    refs.push(`agent:${w.id}`);
  }
  return refs;
}

/**
 * Returns { files: {relativePath: text}, gaps: [string] }.
 * gestalt-flow: what applies everywhere (always-on entries, connectors, the base block).
 * gestalt-<ctx>: what a context adds on top, plus its disables and its block lines.
 */
export function emitKit(way, blocks, profiles = [], agentFiles = {}) {
  const files = {};
  const gaps = [];
  // Workers are global in the topology, so their agents ride on gestalt-flow.
  const agents = agentPrimitives(way, agentFiles, files);
  const docs = [];
  const [base, ...rest] = scenarios(way);
  const harnesses = way.harnesses.filter(h => KIT_HARNESSES.includes(h));
  // The lead's loadout enables only what the lead loads. What a headless worker owns, and a
  // connection a worker holds inline, is disabled for the lead so a global install cannot
  // leak it back in.
  const isolated = new Set(way.connectors.filter(c => c.server && way.topology.workers.some(w => w.mcp.includes(c.id))).map(c => c.ref));
  const connectorEntries = way.connectors.map(c => ({ id: c.id, ref: c.ref, kind: "connector" }));
  const workerOwned = sc => activeEntries(way, sc).filter(e => !leadEntries(way, sc).some(l => l.id === e.id)).map(e => e.ref);
  const baseEntries = [...leadEntries(way, base), ...connectorEntries.filter(c => !isolated.has(c.ref))];
  const baseDisable = [...new Set([...base.active.flatMap(c => way.disable[c] ?? []), ...workerOwned(base), ...isolated])];
  const flow = loadoutFor("gestalt-flow", `${way.person.name}'s way: what every repo gets.`, baseEntries, way, baseDisable, blocks.base.body, { agents, budget: budgetOf(way.budgets) });
  withProfiles(flow, blocks.base.body, profiles.map(pr => [pr, pr.blocks.base.body]), { budgets: way.budgets });
  files["loadouts/gestalt-flow.yaml"] = emitYaml(flow, { header: HEADER });
  docs.push(flow);
  const baseIds = new Set(baseEntries.map(e => e.id));
  for (const sc of rest) {
    const ctx = sc.active[sc.active.length - 1];
    const added = leadEntries(way, sc).filter(e => !baseIds.has(e.id));
    const disable = [...new Set([...(way.disable[ctx] ?? []), ...workerOwned(sc).filter(r => !baseDisable.includes(r))])];
    const block = blocks.contexts.find(b => b.context === ctx);
    const own = way.contexts[ctx].loadouts;
    const loadouts = ["gestalt-flow"];
    const profileBlocks = profiles.map(pr => [pr, pr.blocks.contexts.find(b => b.context === ctx)?.body ?? ""]);
    if (added.length || disable.length || block || profileBlocks.some(([, body]) => body)) {
      const doc = loadoutFor(`gestalt-${ctx}`, `${way.person.name}'s way in ${ctx} repos (${way.contexts[ctx].when}).`, added, way, disable, block?.body);
      withProfiles(doc, block?.body ?? "", profileBlocks);
      files[`loadouts/gestalt-${ctx}.yaml`] = emitYaml(doc, { header: HEADER });
      docs.push(doc);
      loadouts.push(`gestalt-${ctx}`);
    }
    for (const name of own) { loadouts.push(name); gaps.push(`${ctx}: loadout "${name}" is referenced, not generated; it must exist in the warehouse.`); }
    const intent = "Copy into the repo as kit.yaml, then: kitctl apply (it shows the plan and asks first).";
    files[`kit.${ctx}.yaml`] = emitYaml({ schema_version: 1, loadouts, harnesses }, { header: [`kit.yaml for repos where ${way.contexts[ctx].when}.`, intent] });
    for (const pr of profiles) {
      const named = loadouts.map(l => (l.startsWith("gestalt-") ? `${l}:${pr.name}` : l));
      files[`profiles/${pr.name}/kit.${ctx}.yaml`] = emitYaml({ schema_version: 1, loadouts: named, harnesses }, { header: [`kit.yaml for repos where ${way.contexts[ctx].when}, profile ${pr.name}.`, intent] });
    }
  }
  // Missing warehouse primitives are kitctl validate's to report ("missing primitive"); not
  // repeated here. A slot is different: kitctl rejects it unless the primitive declares it.
  for (const doc of docs) for (const [slot, ref] of Object.entries(doc.slots ?? {})) {
    gaps.push(`${ref}: its warehouse primitive must list \`${slot}\` under provides (${doc.name} assigns it that slot).`);
  }
  if (agents.length && way.harnesses.includes("cursor")) gaps.push(`cursor: kitctl places agent primitives for Claude Code and Codex only; ${agents.map(a => `\`${a}\``).join(", ")} ${agents.length > 1 ? "have" : "has"} no Cursor file.`);
  if (way.harnesses.includes("cursor")) gaps.push("cursor: kit.yaml leaves cursor out of harnesses until you add it; kitctl's Cursor facts are unverified, so check the first repo by hand (SETUP.md §6).");
  files["gaps.md"] = `# kitctl gaps\n\nWhat kitctl needs from you before these loadouts apply. \`kitctl validate\` names any primitive missing from your warehouse.\n\n${gaps.length ? gaps.map(g => `- ${g}`).join("\n") : "- Nothing beyond what kitctl validate reports."}\n`;
  return { files, gaps };
}
