// kitctl output. Gestalt never writes native config: it emits loadouts (schema_version 2)
// and per-context kit.yaml intents for kitctl to plan, preview and apply. The managed block
// travels as a loadout's `instructions`, so kitctl owns that text too.
import { activeEntries, leadEntries, scenarios } from "./way.mjs";
import { emitYaml } from "./yaml-emit.mjs";

export const V2_LOADOUT_KEYS = ["schema_version", "name", "description", "extends", "skills", "mcp", "hooks", "plugins", "marketplaces", "slots", "disable", "requires", "optional", "setup", "instructions", "profiles"];
const KIT_HARNESSES = ["claude", "codex"];
const HEADER = ["Generated by gestalt compile from way.yaml. Edit the way, not this file.", "kitctl owns what this writes: kitctl plan, then kitctl apply."];

function loadoutFor(name, description, entries, way, disable, instructions) {
  const plugins = [...new Set(entries.filter(e => e.ref.startsWith("plugin:")).map(e => e.ref))].sort();
  const skills = [...new Set(entries.filter(e => e.ref.startsWith("skill:")).map(e => e.ref))].sort();
  const mcp = {};
  for (const e of entries.filter(x => x.ref.startsWith("mcp:"))) mcp[e.ref.slice(4)] = { primitive: e.ref };
  const slots = {};
  for (const e of entries) if (e.slot) slots[e.slot] = e.ref;
  const doc = { schema_version: 2, name, description, extends: [], plugins, skills, mcp, slots, disable: [...disable].sort() };
  if (instructions) doc.instructions = instructions;
  for (const k of Object.keys(doc)) {
    if (Array.isArray(doc[k]) && doc[k].length === 0 && k !== "extends") delete doc[k];
    else if (doc[k] && typeof doc[k] === "object" && !Array.isArray(doc[k]) && Object.keys(doc[k]).length === 0) delete doc[k];
  }
  return doc;
}

/**
 * Returns { files: {relativePath: text}, gaps: [string] }.
 * gestalt-flow: what applies everywhere (always-on entries, connectors, the base block).
 * gestalt-<ctx>: what a context adds on top, plus its disables and its block lines.
 */
export function emitKit(way, blocks) {
  const files = {};
  const gaps = [];
  const docs = [];
  const [base, ...rest] = scenarios(way);
  const harnesses = way.harnesses.filter(h => KIT_HARNESSES.includes(h));
  // The lead's loadout enables only what the lead loads. What a headless worker owns, and a
  // connection a worker holds inline, is disabled for the lead so a global install cannot
  // leak it back in.
  const isolated = new Set(way.connectors.filter(c => c.server && way.topology.workers.some(w => w.mcp.includes(c.id))).map(c => c.ref));
  const connectorEntries = way.connectors.map(c => ({ id: c.id, ref: c.ref, kind: "connector" }));
  const workerOwned = sc => activeEntries(way, sc).filter(e => !leadEntries(way, sc).some(l => l.id === e.id)).map(e => e.ref);
  const baseEntries = [...leadEntries(way, base), ...connectorEntries.filter(c => !isolated.has(c.ref))];
  const baseDisable = [...new Set([...base.active.flatMap(c => way.disable[c] ?? []), ...workerOwned(base), ...isolated])];
  const flow = loadoutFor("gestalt-flow", `${way.person.name}'s way: what every repo gets.`, baseEntries, way, baseDisable, blocks.base.body);
  files["loadouts/gestalt-flow.yaml"] = emitYaml(flow, { header: HEADER });
  docs.push(flow);
  const baseIds = new Set(baseEntries.map(e => e.id));
  for (const sc of rest) {
    const ctx = sc.active[sc.active.length - 1];
    const added = leadEntries(way, sc).filter(e => !baseIds.has(e.id));
    const disable = [...new Set([...(way.disable[ctx] ?? []), ...workerOwned(sc).filter(r => !baseDisable.includes(r))])];
    const block = blocks.contexts.find(b => b.context === ctx);
    const own = way.contexts[ctx].loadouts;
    const loadouts = ["gestalt-flow"];
    if (added.length || disable.length || block) {
      const doc = loadoutFor(`gestalt-${ctx}`, `${way.person.name}'s way in ${ctx} repos (${way.contexts[ctx].when}).`, added, way, disable, block?.body);
      files[`loadouts/gestalt-${ctx}.yaml`] = emitYaml(doc, { header: HEADER });
      docs.push(doc);
      loadouts.push(`gestalt-${ctx}`);
    }
    for (const name of own) { loadouts.push(name); gaps.push(`${ctx}: loadout "${name}" is referenced, not generated; it must exist in the warehouse.`); }
    files[`kit.${ctx}.yaml`] = emitYaml({ schema_version: 1, loadouts, harnesses }, { header: [`kit.yaml for repos where ${way.contexts[ctx].when}.`, "Copy into the repo as kit.yaml on a branch, add live: true and commit it, then: kitctl plan && kitctl apply --live --yes."] });
  }
  // Missing warehouse primitives are kitctl validate's to report ("missing primitive"); not
  // repeated here. A slot is different: kitctl rejects it unless the primitive declares it.
  for (const doc of docs) for (const [slot, ref] of Object.entries(doc.slots ?? {})) {
    gaps.push(`${ref}: its warehouse primitive must list \`${slot}\` under provides (${doc.name} assigns it that slot).`);
  }
  if (way.harnesses.includes("cursor")) gaps.push("cursor: kit.yaml leaves cursor out of harnesses until you add it; kitctl's Cursor facts are unverified, so check the first repo by hand (SETUP.md §6).");
  files["gaps.md"] = `# kitctl gaps\n\nWhat kitctl needs from you before these loadouts apply. \`kitctl validate\` names any primitive missing from your warehouse.\n\n${gaps.length ? gaps.map(g => `- ${g}`).join("\n") : "- Nothing beyond what kitctl validate reports."}\n`;
  return { files, gaps };
}
