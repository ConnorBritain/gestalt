// WAY.md: the person's way, readable. What runs, in what order, in which kind of repo, on
// which harness and how honestly, what the lead carries and what it delegates.
import { HARNESSES, STAGES } from "./catalog.mjs";
import { activeSteps, scenarios, workerFor } from "./way.mjs";
import { label, how } from "./block.mjs";
import { leadLoad, protocolRules, sessionStartLines, stopGates } from "./lint.mjs";

const cell = s => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

export function renderWay(way, catalog, { lint, blocks, survey = null }) {
  const L = [];
  const p = way.person;
  L.push(`# ${p.name}'s way`, "");
  L.push(`Generated by \`gestalt compile\` from way.yaml. Edit the way, then recompile.`, "");
  if (p.roles?.length) L.push(`**Roles:** ${p.roles.join(", ")}. **Harnesses:** ${way.harnesses.join(", ")}. **Config writer:** ${way.writer}.`, "");
  L.push("## Goals", "");
  for (const g of p.goals) L.push(`- **${g.id}**: ${g.text}`);
  if (p.pains?.length) { L.push("", "Pains this way answers:", ""); for (const x of p.pains) L.push(`- ${x}`); }
  L.push("");

  L.push("## The flow", "");
  L.push("Control moves left to right. Checkers report and never fix; recorders never block. Findings return to you, or to the weekly reflect.", "");
  const ctxNames = Object.keys(way.contexts);
  L.push(`| Stage | Step | Kind | Mode | Contexts | ${way.harnesses.join(" | ")} |`, `|---|---|---|---|---|${way.harnesses.map(() => "---").join("|")}|`);
  for (const stage of STAGES) {
    for (const f of way.flow.filter(x => x.stage === stage)) {
      const ctx = f.in.length === ctxNames.length ? "all" : f.in.join(", ");
      const worker = workerFor(way, f.use);
      const mode = `${f.mode}${f.enforce === "hook" ? " + hook" : ""}${worker ? ` → ${worker.id}` : ""}`;
      L.push(`| ${stage} | ${cell(label(f.use, catalog))} | ${f.step.kind} | ${mode} | ${ctx} | ${way.harnesses.map(h => f.entry.harness?.[h] ?? "none").join(" | ")} |`);
    }
  }
  L.push("", "Harness columns are enforcement: **enforced** (the harness makes it happen), **partial**, **advisory** (written down, nothing makes it happen), **none**.", "");

  L.push("## By kind of repo", "");
  for (const sc of scenarios(way)) {
    const steps = activeSteps(way, sc);
    const ctx = sc.active[sc.active.length - 1];
    const when = way.contexts[ctx].when;
    L.push(`### ${sc.name} (${when === "always" ? "everywhere" : when})`, "");
    const chain = STAGES.map(s => [s, steps.filter(f => f.stage === s)]).filter(([, x]) => x.length).map(([s, x]) => `**${s}** ${x.map(f => label(f.use, catalog)).join(", ")}`);
    L.push(chain.length ? chain.join(" → ") : "_Nothing runs in session here beyond the defaults._", "");
    const stop = stopGates(way, sc);
    if (stop.length) L.push(`- Stop gates: ${stop.length >= 2 ? way.stop_order.filter(id => id.startsWith("platform:") || stop.includes(id)).map(id => label(id, catalog)).join(" → ") : label(stop[0], catalog)}.`);
    const load = leadLoad(way, sc, survey);
    L.push(`- Lead always-on ≈${load.tokens} tokens (budget ${way.budgets.always_on_tokens}), ${load.skills} skills (budget ${way.budgets.skills_per_context}).`);
    const ss = sessionStartLines(way, sc).reduce((n, x) => n + x.lines, 0);
    L.push(`- Session-start lines ${ss} (budget ${way.budgets.session_start_lines}); always-on protocol rules ${protocolRules(way, sc).length} (budget ${way.budgets.protocol_rules}).`);
    if (way.contexts[ctx].loadouts.length) L.push(`- kitctl loadouts: ${way.contexts[ctx].loadouts.join(", ")}.`);
    if ((way.disable[ctx] ?? []).length) L.push(`- Disabled here: ${way.disable[ctx].join(", ")}.`);
    L.push("");
  }

  L.push("## Lead and workers", "");
  const tiers = Object.entries(way.topology.tiers);
  if (tiers.length) {
    L.push("| Harness | lead | worker | critic |", "|---|---|---|---|");
    for (const [h, m] of tiers) L.push(`| ${h} | ${m.lead ?? "—"} | ${m.worker ?? "—"} | ${m.critic ?? "—"} |`);
    L.push("");
  }
  if (way.topology.lead.keeps.length) L.push(`The lead keeps in its own context: ${way.topology.lead.keeps.map(id => label(id, catalog)).join(", ")}.`, "");
  if (way.topology.workers.length) {
    L.push("| Worker | Tier | Mechanism | Does | Called when | Isolates |", "|---|---|---|---|---|---|");
    for (const w of way.topology.workers) {
      const iso = { subagent: "model tier; MCP when the connector has an inline server", headless: "model tier, plugins, MCP (its hooks leave the lead)", "agent-file": "model tier, clean context", script: "no model at all" }[w.mechanism];
      L.push(`| ${w.id} | ${w.tier} | ${w.mechanism} | ${w.uses.map(u => label(u, catalog)).join(", ")} | ${cell(w.route ?? "—")} | ${iso} |`);
    }
    L.push("");
  } else L.push("_No workers: everything runs in the lead._", "");

  if (way.links.length) {
    L.push("## Hand-offs", "");
    for (const l of way.links) L.push(`- ${label(l.from, catalog)} **${l.on}** → ${l.to === "user" ? "you" : label(l.to, catalog)}${l.as ? ` (as ${l.as})` : ""}, ${l.via === "instruction" ? "by a line in the block" : "by hand"}.`);
    L.push("");
  }

  L.push("## Reflect", "");
  let anyReflect = false;
  for (const [cadence, items] of Object.entries(way.reflect)) {
    if (!items.length) continue;
    anyReflect = true;
    const where = r => (r.in.length < Object.keys(way.contexts).length ? ` [in ${r.in.join(", ")} repos]` : "");
    if (cadence === "on_enter") L.push(`- **on entering a repo, in order**: ${items.map((r, i) => `${i + 1}. ${label(r.use, catalog)} (${r.step.invoke})${where(r)}`).join(" ")}`);
    else L.push(`- **${cadence}**: ${items.map(r => `${label(r.use, catalog)} (${r.step.invoke})${where(r)}`).join("; ")}`);
  }
  if (!anyReflect) L.push("- No rituals yet. A weekly `/gestalt:trim` is the cheapest one to start with.");
  L.push("", "Rituals never go in the always-on block; they live here and in your calendar.", "");

  L.push("## The block", "");
  L.push(`Base block ≈${blocks.base.tokens} tokens (budget ${way.budgets.block_tokens})${blocks.contexts.length ? `; context blocks: ${blocks.contexts.map(b => `${b.context} ≈${b.tokens}`).join(", ")}` : ""}.`, "");
  L.push("```markdown", blocks.base.text.trimEnd(), "```", "");
  for (const b of blocks.contexts) L.push("```markdown", b.text.trimEnd(), "```", "");

  L.push("## Lint", "");
  const shown = lint.problems.filter(x => x.severity !== "error");
  if (!shown.length) L.push("Clean: no warnings, no waivers.");
  for (const x of shown) L.push(`- ${x.severity === "info" ? "info" : "warn"} **${x.code}** ${x.where}: ${x.message}${x.waived ? ` _(waived: ${x.waived})_` : ""}`);
  L.push("");
  return `${L.join("\n")}\n`;
}

export { HARNESSES, how };
